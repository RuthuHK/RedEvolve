"""Tensor Trust extraction-robustness held-out set (v1.1): fetch, build the id manifest, verify.

Tensor Trust's data has no licence, so its texts are never committed or redistributed. The repo
holds only ``data/heldout/tensortrust_ids.yaml`` (sample ids + text hashes); anyone can rebuild
the texts locally from the pinned file:

    python -I scripts/build_tensortrust.py --fetch    # download the pinned file to .cache/
    python -I scripts/build_tensortrust.py --verify   # rebuild + check every hash

``--build`` (run once, 2026-11-24, before any v1.1 run) applies the pre-registered filters and
sample (``redevolve.heldout.build_manifest``) and writes the manifest; it refuses to overwrite
an existing one (the set is frozen). Prints counts and hashes only, never attack texts.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

import httpx

from redevolve.benign import load_benign
from redevolve.guardrail import CLASSIFIER_EXAMPLES
from redevolve.heldout import (
    HeldoutError,
    build_manifest,
    dump_manifest,
    file_sha256,
    load_heldout,
    load_manifest,
    read_jsonl,
)
from redevolve.seeds import load_seeds

COMMIT = "747a75e096761ebc01bd3970158827326b4add23"
PATH = "benchmarks/extraction-robustness/v1/extraction_robustness_dataset.jsonl"
SOURCE = {
    "dataset": "Tensor Trust extraction-robustness benchmark v1",
    "repo": "https://github.com/HumanCompatibleAI/tensor-trust-data",
    "revision": COMMIT,
    "file": PATH,
    "url": f"https://raw.githubusercontent.com/HumanCompatibleAI/tensor-trust-data/{COMMIT}/{PATH}",
    "sha256": "4090f9f57b6df69cc32d7669ac991e3fd53e6e2bb616a5e6f45dac79c183ee4c",
    "id_field": "sample_id",
    "text_field": "attack",  # only the attack; TT's pre/post prompts and access code are unused
    "license": "none found (GitHub repo and Hugging Face mirror, checked 2026-11-23)",
    "redistributed": False,
    "cache_path": ".cache/tensortrust-747a75e0/extraction_robustness_dataset.jsonl",
    "citation": "Toyer et al., Tensor Trust: Interpretable Prompt Injection Attacks from an "
    "Online Game (arXiv:2311.01011)",
}
NAME, PREFIX, FAMILY = "tensortrust", "tt", "tensortrust"
N, SALT, MAX_CHARS = 200, "tensortrust-v1.1", 4000  # owner decision 2026-11-24
OUT = Path("data/heldout/tensortrust_ids.yaml")
HEADER = (
    "# Held-out attack ID MANIFEST (v1.1). GENERATED by scripts/build_tensortrust.py from\n"
    "# Tensor Trust's extraction-robustness benchmark @ {revision}. No licence was found, so the\n"
    "# texts are NOT in this repo: rebuild them locally with --fetch. Frozen: never edit by hand\n"
    "# (manifest_sha256 is checked on load and pinned in tests/test_heldout.py).\n"
)


def check_prompts() -> list[str]:
    """The prompts of scripts/check_classifier.py (dev data), read without importing it."""
    tree = ast.parse(Path(__file__).with_name("check_classifier.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "PROMPTS" for t in node.targets
        ):
            return [p for _, p in ast.literal_eval(node.value)]
    raise SystemExit("PROMPTS not found in scripts/check_classifier.py")


def overlap_texts() -> list[str]:
    """Dev texts (as for Gandalf) plus both Gandalf variants: no shared 8-word runs allowed."""
    texts = [s.prompt for s in load_seeds("data/seeds.yaml").seeds]
    texts += [p.prompt for p in load_benign("data/benign.yaml").prompts]
    texts += [t for t, _ in CLASSIFIER_EXAMPLES] + check_prompts()
    for name in ("gandalf", "gandalf_code"):
        texts += [a.prompt for a in load_heldout(f"data/heldout/{name}.yaml").attacks]
    return texts


def fetch() -> int:
    dest = Path(SOURCE["cache_path"])
    if not dest.is_file():
        dest.parent.mkdir(parents=True, exist_ok=True)
        r = httpx.get(SOURCE["url"], follow_redirects=True, timeout=60)
        r.raise_for_status()
        dest.write_bytes(r.content)
    digest = file_sha256(dest)
    if digest != SOURCE["sha256"]:
        print(f"sha256 mismatch for {dest}: {digest}", file=sys.stderr)
        return 1
    print(f"{dest}: sha256 ok")
    return 0


def build() -> int:
    if OUT.exists():
        print(f"{OUT} exists and is frozen; not overwriting", file=sys.stderr)
        return 1
    src = Path(SOURCE["cache_path"])
    if not src.is_file() or file_sha256(src) != SOURCE["sha256"]:
        print("pinned source missing or changed: run --fetch first", file=sys.stderr)
        return 1
    rows = read_jsonl(src, id_field=SOURCE["id_field"], text_field=SOURCE["text_field"])
    manifest, hs = build_manifest(
        NAME,
        PREFIX,
        FAMILY,
        rows,
        dev_texts=overlap_texts(),
        n=N,
        salt=SALT,
        max_chars=MAX_CHARS,
        source=SOURCE,
    )
    dump_manifest(manifest, OUT, header=HEADER.format(**SOURCE))
    f = manifest["filters"]
    print(f"rows {f['rows']}, kept {f['kept']}, sampled {f['sampled']}; dropped {f['dropped']}")
    print(f"manifest_sha256 {manifest['manifest_sha256']}")
    print(f"set_sha256      {hs.sha256}")
    return 0


def verify() -> int:
    try:
        hs = load_manifest(OUT)
    except HeldoutError as e:
        print(e, file=sys.stderr)
        return 1
    print(f"{hs.name}: {len(hs.attacks)} attacks rebuilt, every hash ok, set sha256 {hs.sha256}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--fetch", action="store_true", help="download + check the pinned file")
    g.add_argument("--build", action="store_true", help="write the manifest (once; frozen)")
    g.add_argument("--verify", action="store_true", help="rebuild the texts and check hashes")
    args = ap.parse_args()
    return fetch() if args.fetch else build() if args.build else verify()


if __name__ == "__main__":
    raise SystemExit(main())
