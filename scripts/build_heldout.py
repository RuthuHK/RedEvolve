"""Build the frozen held-out attack sets (M8) from the pinned Gandalf test split.

Run once; the output in data/heldout/ is committed and its hashes pinned in
tests/test_heldout.py. Needs the optional ``data`` extra (pyarrow). Prints counts and hashes
only, never prompt texts.

Download the pinned file first (into its own empty directory):

    mkdir -p .cache/gandalf-04737b65
    curl -sSL -o .cache/gandalf-04737b65/test.parquet \\
      https://huggingface.co/datasets/Lakera/gandalf_ignore_instructions/resolve/04737b65e90a6794ec227012e4a255a7def6344b/data/test-00000-of-00001-bc92128b9288a6d1.parquet

Usage: python -I scripts/build_heldout.py [PARQUET] [--out data/heldout]
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import sys
from pathlib import Path

from redevolve.benign import load_benign
from redevolve.guardrail import CLASSIFIER_EXAMPLES
from redevolve.heldout import build_set, dump_set, filter_rows
from redevolve.seeds import load_seeds

SOURCE = {
    "dataset": "Lakera/gandalf_ignore_instructions",
    "url": "https://huggingface.co/datasets/Lakera/gandalf_ignore_instructions",
    "revision": "04737b65e90a6794ec227012e4a255a7def6344b",
    "file": "data/test-00000-of-00001-bc92128b9288a6d1.parquet",
    "sha256": "56b646d133335ebc535266bd55dbe1b5bee7caa4b95bf49d040684b9b5dd9972",
    "split": "test",
    "column": "text",
    "license": "MIT",
    "attribution": "Gandalf prompt-injection dataset by Lakera (MIT); see data/heldout/LICENSE",
}
SETS = (  # (name, id prefix, transform)
    ("gandalf", "gv", "verbatim"),
    ("gandalf_code", "gc", "password-to-code"),
)
HEADER = (
    "# Held-out attack set for the M8 guardrail evaluation. GENERATED by scripts/build_heldout.py\n"
    "# from {dataset} @ {revision} ({split} split), {license} licence, (c) Lakera; see\n"
    "# data/heldout/LICENSE. Frozen: never edit by hand (the stored sha256 is checked on load\n"
    "# and pinned in tests/test_heldout.py).\n"
)


def check_prompts() -> list[str]:
    """The prompts of scripts/check_classifier.py (dev data), read without importing it."""
    tree = ast.parse(Path(__file__).with_name("check_classifier.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "PROMPTS" for t in node.targets
        ):
            return [p for _, p in ast.literal_eval(node.value)]
    raise SystemExit("PROMPTS not found in scripts/check_classifier.py")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("parquet", nargs="?", default=".cache/gandalf-04737b65/test.parquet")
    ap.add_argument("--out", default="data/heldout")
    args = ap.parse_args()
    raw = Path(args.parquet).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE["sha256"]:
        print(f"sha256 mismatch: {digest} (expected {SOURCE['sha256']})", file=sys.stderr)
        return 1
    import pyarrow.parquet as pq  # optional dependency, only needed here

    col = pq.read_table(args.parquet).column(SOURCE["column"]).to_pylist()
    rows = [x if isinstance(x, str) else "" for x in col]
    dev = [s.prompt for s in load_seeds("data/seeds.yaml").seeds]
    dev += [p.prompt for p in load_benign("data/benign.yaml").prompts]
    dev += [t for t, _ in CLASSIFIER_EXAMPLES]
    dev += check_prompts()
    res = filter_rows(rows, dev)
    filters = {
        "rows_in": len(rows),
        "kept": len(res.kept),
        **{f"dropped_{k}": v for k, v in res.dropped.items()},
    }
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    print(f"source rows {len(rows)}, kept {len(res.kept)}")
    for k, v in res.dropped.items():
        print(f"  dropped {k}: {len(v)} rows {v}")
    for name, prefix, transform in SETS:
        s = build_set(name, prefix, transform, res.kept, source=SOURCE, filters=filters)
        dump_set(s, out / f"{name}.yaml", header=HEADER.format(**SOURCE))
        changed = sum(a.prompt != t for a, (_, t) in zip(s.attacks, res.kept, strict=True))
        print(f"{name}: {len(s.attacks)} attacks, {changed} changed by transform, {s.sha256}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
